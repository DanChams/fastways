// Install playwright-core outside the checkout; set PLAYWRIGHT_MODULE to its index.mjs.
import assert from 'node:assert/strict';
import { mkdir, readFile } from 'node:fs/promises';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright-core');
const base = process.env.STUDIO_BASE_URL || 'http://127.0.0.1:8789';
if (!['localhost', '127.0.0.1', '[::1]'].includes(new URL(base).hostname)) throw new Error('Ce test utilise uniquement un serveur local sans clé IA.');
const output = process.env.STUDIO_TEST_OUTPUT || '/tmp/fastway-studio-tests';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1120 } });
const cleanupIds = [];
const title = `Test atelier ${Date.now()}`;
try {
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(base + '/studio');
  await page.waitForFunction(() => !document.querySelector('fieldset').disabled);
  await page.screenshot({ path: output + '/studio-empty.png', fullPage: true });
  const status = await (await page.request.get(base + '/api/studio-image')).json();
  assert.equal(status.configured, false, 'This test must run without a paid image API key.');
  assert.equal(status.available, false);
  assert.equal(await page.getByRole('button', { name: 'Générer l’image du produit' }).isDisabled(), true);
  const denied = await page.request.post(base + '/api/studio-image', { multipart: { prompt: 'test' } });
  assert.equal(denied.status(), 503);
  const csrf = await page.request.post(base + '/api/studio-image', { headers: { origin: 'https://untrusted.example' }, multipart: { prompt: 'test' } });
  assert.equal(csrf.status(), 403);
  await page.getByLabel('1. Référence d’ambiance', { exact: true }).setInputFiles(new URL('../public/studio-demo.png', import.meta.url).pathname);
  await page.getByLabel('2. Photo du produit', { exact: true }).setInputFiles(new URL('../public/studio-demo.png', import.meta.url).pathname);
  await page.getByRole('tab', { name: /Miniature/ }).click();
  await page.getByLabel('Image personnalisée').check();
  await page.getByLabel('Importer la miniature', { exact: true }).setInputFiles(new URL('../public/fastway-logo.png', import.meta.url).pathname);
  await page.getByRole('tab', { name: /Textes/ }).click();
  await page.getByLabel('Nom du produit', { exact: true }).fill(title);
  await page.getByLabel('Prix en dollars', { exact: true }).fill('120');
  await page.getByLabel('Description et caractéristiques', { exact: true }).fill('Coloris blanc\nFormat de table');
  await page.getByLabel('Date de publication', { exact: true }).fill('2026-11-18');
  const save = page.getByRole('button', { name: 'Enregistrer dans le calendrier', exact: true });
  await page.waitForFunction(() => !Array.from(document.querySelectorAll('button')).find(b => b.textContent.includes('Enregistrer dans le calendrier')).disabled);
  await page.screenshot({ path: output + '/studio-edit.png', fullPage: true });
  const handle = await page.getByRole('button', { name: 'Déplacer le titre' }).boundingBox();
  await page.mouse.move(handle.x + 10, handle.y + 8); await page.mouse.down();
  await page.mouse.move(handle.x + 15, handle.y + 8, { steps: 3 }); await page.mouse.up();
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Exporter le PNG', exact: true }).click();
  const download = await downloadEvent; assert.equal(download.suggestedFilename(), 'fastway-affiche.png');
  await download.saveAs(output + '/export.png');
  const png = await readFile(output + '/export.png');
  assert.equal(png.readUInt32BE(16), 1080); assert.equal(png.readUInt32BE(20), 1350);
  const draftEvent = page.waitForEvent('download'); await page.getByRole('button', { name: 'Brouillon', exact: true }).click();
  const draft = await draftEvent; await draft.saveAs(output + '/test-draft.json');
  const before = await (await page.request.get(base + '/api/posts')).json();
  await save.click(); await page.getByRole('button', { name: 'Enregistré dans le calendrier', exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Enregistré dans le calendrier', exact: true }).isDisabled(), true);
  const after = await (await page.request.get(base + '/api/posts')).json();
  const created = after.filter(x => !before.some(y => y.id === x.id)); cleanupIds.push(...created.map(post => post.id));
  assert.equal(created.length, 1); assert.equal(created[0].title, title);
  assert.notEqual(created[0].thumbnail.id, created[0].assets[0].id);
  for (const asset of [created[0].assets[0], created[0].thumbnail]) {
    const file = await page.request.get(base + asset.url); assert.equal(file.status(), 200); assert.match(file.headers()['content-type'], /image\/png/);
  }
  await page.waitForTimeout(1000); await page.reload();
  await page.waitForFunction(() => !document.querySelector('fieldset').disabled);
  await page.getByRole('tab', { name: /Textes/ }).click();
  assert.equal(await page.getByLabel('Nom du produit', { exact: true }).inputValue(), title);
  assert.equal(await page.getByLabel('Prix en dollars', { exact: true }).inputValue(), '120');
  await page.getByLabel('Nom du produit', { exact: true }).fill('Texte remplacé');
  await page.locator('input[type=file][accept*="json"]').setInputFiles(output + '/test-draft.json');
  await page.waitForFunction(expected => document.querySelector('textarea[maxlength="150"]').value === expected, title);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: output + '/studio-mobile.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  await page.goto(base + '/?date=2026-11-18');
  await page.getByRole('heading', { name: 'Novembre 2026', exact: true }).waitFor();
  assert.match(await page.locator('.mobile-dates [aria-pressed=true]').textContent(), /^18/);
  assert.ok((await page.locator('.mobile-posts').textContent()).includes(title));
  assert.deepEqual(errors, []);
  console.log('PASS: dual-image transposition, missing-key/CSRF errors, independent thumbnail, editable text/drag, PNG 1080x1350, JSON draft import/export, auto-restore, D1/R2 save, duplicate-click prevention, mobile width, calendar selected date. Real AI generation unrun.');
} finally {
  for (const id of cleanupIds) await page.request.delete(base + '/api/posts', { data: { id } }).catch(() => {});
  await browser.close();
}
